-- stage 1
-- This query combines data retrieval from FIRMS, CUSTS,  AGNTS , ENTITIES , ACNTS , ACNTS_DTLS tables
SELECT 
    "FIRMS"."FIRM_LONG_NAME",
    "FIRMS"."FIRM_CODE",
    "ACNTS"."ACNT_CODE",
    "CUSTS"."CUST_CODE",
    "CUSTS"."AGNT_CODE",
    "AGNTS"."CUST_LONG_DSCR" AS "AGNT_CUST_LONG_DSCR",
    "CUSTS"."CUST_LONG_DSCR",
    "CUSTS"."ENT_CODE",
    "CUSTS"."CRE_DATE",
    "CUSTS"."ACTV_Y_N",
    "CUSTS"."MAX_CREDIT",
    "CUSTS"."RLBL",
    "ENTITIES"."ENT_LONG_NAME",
    "ACNTS_DTLS"."PMNT_TYPE",
    "DOR_CUSTS"."CLOSE_RSN", 
    "DOR_CUSTS"."CLOSE_DATE"
FROM 
    "DBTRANS"."FIRMS" "FIRMS"
    JOIN "DBTRANS"."CUSTS" "CUSTS"
        ON "FIRMS"."FIRM_CODE" = "CUSTS"."FIRM_CODE"
    LEFT JOIN "DBTRANS"."CUSTS" "AGNTS"
        ON "CUSTS"."FIRM_CODE" = "AGNTS"."FIRM_CODE"
        AND "CUSTS"."AGNT_CODE" = "AGNTS"."CUST_CODE"
    LEFT JOIN "DBTRANS"."ENTITIES" "ENTITIES"
        ON "CUSTS"."ENT_CODE" = "ENTITIES"."ENT_CODE"
        
    LEFT OUTER JOIN "DBTRANS"."ACNTS" "ACNTS"
        ON "CUSTS"."ACNT_CODE" = "ACNTS"."ACNT_CODE"
        AND "CUSTS"."FIRM_CODE" = "ACNTS"."FIRM_CODE"
 LEFT OUTER JOIN "DBTRANS"."ACNTS_DTLS" "ACNTS_DTLS"
        ON "ACNTS"."FIRM_CODE" = "ACNTS_DTLS"."FIRM_CODE"
        AND "ACNTS"."ACNT_CODE" = "ACNTS_DTLS"."ACNT_CODE"
          INNER JOIN "DBTRANS"."DOR_CUSTS" "DOR_CUSTS"
        ON "CUSTS"."FIRM_CODE" = "DOR_CUSTS"."FIRM_CODE"
        AND "CUSTS"."CUST_CODE" = "DOR_CUSTS"."CUST_CODE"
WHERE 
   "FIRMS"."FIRM_CODE" = 21 -- External parameter for filtering by firm_code
    AND "CUSTS"."CUST_CODE" = '1' -- External parameter for filtering by cust_code
 -- "ACNTS"."ACNT_CODE" = 100
ORDER BY 
    "CUSTS"."AGNT_CODE", 
    "CUSTS"."CUST_LONG_DSCR";
