-- Stage 2: Retrieve Logistic Document Details
-- This stage retrieves data from the LGSTC_ACTL_DOCS table, which depends on firm_code and cust_code
SELECT 
    "LGSTC_ACTL_DOCS"."DOC_NBR",
    "LGSTC_ACTL_DOCS"."EVNT_DATE",
    "LGSTC_ACTL_DOCS"."PRMY_TRNS_CLSS",
    "LGSTC_ACTL_DOCS"."TRNS_STAT",
    "LGSTC_ACTL_DOCS"."FREE_FLD_1"
FROM 
    "DBTRANS"."LGSTC_ACTL_DOCS" "LGSTC_ACTL_DOCS"
WHERE 
    "LGSTC_ACTL_DOCS"."FIRM_CODE" = 21 -- External parameter for filtering by firm_code
    AND "LGSTC_ACTL_DOCS"."CUST_CODE" = '1' -- External parameter for filtering by cust_code
    AND ("LGSTC_ACTL_DOCS"."PRMY_TRNS_CLSS" = 323 OR "LGSTC_ACTL_DOCS"."PRMY_TRNS_CLSS" = 325)
    AND ("LGSTC_ACTL_DOCS"."TRNS_STAT" >= 20 AND "LGSTC_ACTL_DOCS"."TRNS_STAT" <= 40)
    AND "LGSTC_ACTL_DOCS"."EVNT_DATE" >= TO_DATE('01-01-2007 00:00:00', 'DD-MM-YYYY HH24:MI:SS')
    AND ("LGSTC_ACTL_DOCS"."FREE_FLD_1" = '1' OR "LGSTC_ACTL_DOCS"."FREE_FLD_1" = '2');

